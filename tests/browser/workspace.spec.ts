test("password change, recovery link and suspension revoke browser access", async ({ browser }) => {
  const clientContext = await browser.newContext(), adminContext = await browser.newContext(), recoveryContext = await browser.newContext();
  const client = await clientContext.newPage(), admin = await adminContext.newPage(), recovery = await recoveryContext.newPage();
  const email = `password-${randomUUID()}@example.test`;
  const db = openDatabase(join(process.env.RENTX_E2E_DATA_DIR!, "rentx.db"));
  try { new Store(db).createUser("Compte récupération", email, await hashPassword(password)); } finally { db.close(); }
  try {
    await login(client, email);
    await client.goto("/compte/mot-de-passe");
    await client.getByLabel("Mot de passe actuel").fill(password);
    await client.locator('input[name="password"]').fill("Changed-browser-password-456!");
    await client.getByLabel("Confirmer le mot de passe").fill("Changed-browser-password-456!");
    await client.getByRole("button", { name: "Enregistrer mon mot de passe" }).click();
    await expect(client.getByRole("status")).toContainText("Mot de passe modifié");
    await login(admin, adminEmail);
    await admin.goto(`/gestion/utilisateurs?q=${encodeURIComponent(email)}`);
    await admin.getByText("Récupération du compte", { exact: true }).click();
    await admin.getByLabel("J’ai vérifié l’identité du titulaire.").check();
    await admin.getByRole("button", { name: "Créer un lien de récupération" }).click();
    const link = admin.getByRole("link", { name: "Lien de récupération personnel ↗" });
    await expect(link).toBeVisible();
    const href = (await link.getAttribute("href"))!;
    await recovery.goto(href);
    await recovery.locator('input[name="password"]').fill(password);
    await recovery.getByLabel("Confirmer le mot de passe").fill(password);
    await recovery.getByRole("button", { name: "Enregistrer mon mot de passe" }).click();
    await expect(recovery.getByRole("status")).toContainText("réinitialisé");
    await client.goto("/compte"); await expect(client).toHaveURL(/\/connexion/);
    await login(client, email);
    await admin.getByLabel("Compte actif").uncheck();
    await admin.getByRole("button", { name: "Enregistrer les accès" }).click();
    await expect(admin.getByText("Client · Suspendu", { exact: true })).toBeVisible();
    await client.goto("/compte"); await expect(client).toHaveURL(/\/connexion/);
    await client.getByLabel("Adresse e-mail").fill(email); await client.locator('input[name="password"]').fill(password);
    await client.getByRole("button", { name: "Se connecter ↗" }).click();
    await expect(client.locator('.form-error[role="alert"]')).toContainText("incorrect");
    const result = await client.request.get("/api/auth/status");
    expect(result.headers()["cache-control"]).toContain("no-store");
    expect((await result.json()).connected).toBe(false);
  } finally { await Promise.all([clientContext.close(), adminContext.close(), recoveryContext.close()]); }
});


